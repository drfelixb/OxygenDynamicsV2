function mustError(functionHandle,expectedMessage)

try
    functionHandle();
catch ME
    assert(contains(ME.message,expectedMessage), ...
        'Expected error containing "%s", but got "%s".',expectedMessage,ME.message);
    return
end

error('Expected an error containing "%s", but no error was thrown.',expectedMessage);

end

