function Value = firstTableTextValue(TableVariable)

if iscell(TableVariable)
    Value = string(TableVariable{1});
elseif isstring(TableVariable) || iscategorical(TableVariable)
    Value = string(TableVariable(1));
elseif ischar(TableVariable)
    Value = string(strtrim(TableVariable(1,:)));
else
    Value = string(TableVariable(1));
end

end

