function SmokeResult = runOxygenPipelineSmokeTest()
%RUNOXYGENPIPELINESMOKETEST Quick helper smoke test for TIFF handling.
%
% This test creates a temporary recording folder with one raw TIFF and one
% denoised TIFF, then exercises the shared inspection, validation, loading,
% and output-folder helpers. It does not run the full scientific analysis.

setupOxygenDynamicsPath();

MasterFolder = fileparts(mfilename('fullpath'));
SmokeFixture = createSmokeRecordingFixture();
CleanupObj = SmokeFixture.CleanupObj; %#ok<NASGU>
SmokeRoot = SmokeFixture.Root;
RecordingFolder = SmokeFixture.RecordingFolder;
RawData = SmokeFixture.RawData;
DenoisedData = SmokeFixture.DenoisedData;
RawPath = SmokeFixture.RawPath;
DenoisedPath = SmokeFixture.DenoisedPath;
SaveOptions = SmokeFixture.SaveOptions;

SmokeResult = struct();
SmokeResult.Root = SmokeRoot;
SmokeResult.RecordingFolder = RecordingFolder;
SmokeResult.RawPath = RawPath;
SmokeResult.DenoisedPath = DenoisedPath;

[TiffStatus,Validation,Metadata] = runTiffInputSmokeAssertions(RecordingFolder,RawData,DenoisedData,RawPath);
runEventSmokeAssertions();
runTableSmokeAssertions();

OutputFolders = runMasterOutputSmokeAssertions(SmokeRoot,RecordingFolder,RawPath,DenoisedPath);

runUtilitySmokeAssertions();
runSummaryFigureSmokeAssertions(SmokeRoot);
runPipelineVerificationReportSmokeAssertions(SmokeRoot);
runVascularAnalysisSmokeAssertions(SmokeRoot);
SmokeBLIEventSnips = runBehaviourTraceSmokeAssertions();
runStatsWorkbookSmokeAssertions(SmokeRoot);
runStatsTraceExportSmokeAssertions(SmokeBLIEventSnips);
[SmokeBehaviourFolder,SmokeCreatedMetadata,SmokeStatsMetadata] = runStatsInputLoadingSmokeAssertions(SmokeRoot);
[SmokeSinkSchemaTable,SmokeSurgeSchemaTable,SmokeSurgeEventTable] = runStatsSinkSurgeRecordingSmokeAssertions( ...
    SmokeRoot,SmokeCreatedMetadata);
SmokeRecordingCells = runStatsFullRecordingLoaderSmokeAssertions(SmokeRoot,SmokeBehaviourFolder, ...
    SmokeSinkSchemaTable,SmokeSurgeSchemaTable,SmokeSurgeEventTable);
runStatsCurationRowSmokeAssertions(SmokeRoot,SmokeCreatedMetadata);
runStatsMetricTimeSeriesSmokeAssertions(SmokeStatsMetadata);
runHypoxicEventSpecificExportSmokeAssertions(SmokeRoot);
runStatsBehaviourFilterSummarySmokeAssertions(SmokeRoot,SmokeRecordingCells);

MismatchFolder = createMismatchSmokeRecording(SmokeRoot,RawData,DenoisedData,SaveOptions);
MismatchValidation = validateOxygenRecording(MismatchFolder,1,2.5,false,Metadata);
assert(~MismatchValidation.IsValid,'Mismatched raw/denoised TIFFs should fail validation.');
assert(any(contains(MismatchValidation.Errors,'matching width, height, and frame count')), ...
    'Mismatched raw/denoised TIFFs failed for an unexpected reason.');
mustError(@() loadOxygenStacks(MismatchFolder),'same x/y dimensions and number of frames');

MultipleRawFolder = createMultipleRawSmokeRecording(SmokeRoot,RawData,SaveOptions);
MultipleRawValidation = runOneOutputSilently( ...
    @() validateOxygenRecording(MultipleRawFolder,1,2.5,false,Metadata));
assert(~MultipleRawValidation.IsValid,'Multiple raw TIFFs should fail validation.');
assert(any(contains(MultipleRawValidation.Errors,'More than one original/raw tif')), ...
    'Multiple raw TIFFs failed for an unexpected reason.');
mustErrorSilently(@() loadOxygenStacks(MultipleRawFolder),'More than one original/raw tif');

[~,~,QCSummary] = runWrapperSmokeAssertions(SmokeRoot,RecordingFolder, ...
    RawData,Validation,OutputFolders);
runStatsOutputSelectionSmokeAssertions(SmokeRoot);
runRegressionSmokeAssertions(SmokeRoot);

SmokeResult.TiffStatus = TiffStatus;
SmokeResult.Validation = Validation;
SmokeResult.MismatchValidation = MismatchValidation;
SmokeResult.MultipleRawValidation = MultipleRawValidation;
SmokeResult.QCSummary = QCSummary;
SmokeResult.OutputFolders = OutputFolders;
SmokeResult.Passed = true;

fprintf('Oxygen pipeline smoke test passed in temporary folder:\n%s\n',SmokeRoot);

cd(MasterFolder);
end

function [TiffStatus,Validation,Metadata] = runTiffInputSmokeAssertions(RecordingFolder,RawData,DenoisedData,RawPath)

TiffStatus = inspectOxygenTiffs(RecordingFolder);
assert(isscalar(TiffStatus.RawFiles),'Smoke test expected exactly one raw TIFF.');
assert(isscalar(TiffStatus.DenoisedFiles),'Smoke test expected exactly one denoised TIFF.');

Metadata = createSmokeMetadata();
Validation = validateOxygenRecording(RecordingFolder,1,2.5,false,Metadata);
assert(Validation.IsValid,'Smoke test validation failed: %s',strjoin(Validation.Errors,'; '));
WrapperMetadata = createRecordingMetadata('SmokeMouse','SmokeCondition','SmokeDrug','SmokeGenotype','SmokePromoter');
assert(isequal(WrapperMetadata,Metadata),'Shared metadata helper did not create expected metadata.');

[IM_Raw,IM_NoNoise,Miu,Miu_NoNoise,RawTifFile,RawFile,DenoisedFile] = loadOxygenStacks(RecordingFolder);
assert(isequal(size(IM_Raw),size(RawData)),'Raw stack size mismatch.');
assert(isequal(size(IM_NoNoise),size(DenoisedData)),'Denoised stack size mismatch.');
assert(strcmp(RawTifFile.name,'Smoke_original.tif'),'Raw TIFF selection mismatch.');
assert(strcmp(RawFile.name,'Smoke_original.tif'),'Raw file metadata mismatch.');
assert(strcmp(DenoisedFile.name,'Smoke_denoised.tif'),'Denoised file metadata mismatch.');
assert(numel(Miu)==size(RawData,3),'Raw mean trace length mismatch.');
assert(numel(Miu_NoNoise)==size(DenoisedData,3),'Denoised mean trace length mismatch.');

RawOnly = loadRawTiffStack(RecordingFolder);
assert(isequal(size(RawOnly),size(RawData)),'Raw-only stack size mismatch.');

[OxygenAnalysisParams,OxygenParamVars] = createOxygenMasterParams(2.5,1);
assert(OxygenAnalysisParams.PercentileDetectionThres==99,'Oxygen master parameter helper returned unexpected detection percentile.');
assert(OxygenParamVars.Pixel_frame==20,'Oxygen master parameter helper returned unexpected pixel frame.');
[OxygenInputData,OxygenAnalysisInfo] = loadOxygenMasterInputs(RecordingFolder,OxygenAnalysisParams);
assert(strcmp(OxygenInputData.DatafileID,'RecordingSmoke'),'Oxygen master input helper returned unexpected DatafileID.');
assert(strcmp(OxygenAnalysisInfo.QuantificationSource,'Original/raw TIFF'), ...
    'Oxygen master input helper returned unexpected quantification provenance.');

[IOSAnalysisParams,IOSParamVars] = createiOSMasterParams(2.5,1);
assert(IOSAnalysisParams.PercentileDetectionThres==98,'iOS master parameter helper returned unexpected detection percentile.');
assert(IOSParamVars.Pixel_frame==20,'iOS master parameter helper returned unexpected pixel frame.');
[IOSInputData,IOSAnalysisInfo] = loadiOSMasterInputs(RecordingFolder,IOSAnalysisParams);
assert(strcmp(IOSInputData.DatafileID,'RecordingSmoke'),'iOS master input helper returned unexpected DatafileID.');
assert(strcmp(IOSAnalysisInfo.RawFile,RawPath),'iOS master input helper returned unexpected raw-file provenance.');

RecordingArea = computeRecordingArea(single(RawData),2.5,30, ...
    'recAreaBinHalfSizeUm',5,'recAreaMinCoverageFraction',0.5);
assert(islogical(RecordingArea.Filter),'Recording-area helper returned a non-logical filter.');
assert(RecordingArea.AreaUm2>=0,'Recording-area helper returned a negative area.');
assert(size(RecordingArea.Bins,2)==2,'Recording-area helper returned unexpected ROI-bin coordinates.');

[SmokeZ,SmokeSmoothed] = preprocessDetectionStack(single(RawData),2);
assert(isequal(size(SmokeZ),size(RawData)),'Detection preprocessing helper returned unexpected z-stack size.');
assert(isequal(size(SmokeSmoothed),size(RawData)),'Detection preprocessing helper returned unexpected smoothed-stack size.');
[~,SmokeSmoothedUint8] = preprocessDetectionStack(single(RawData),2,'scaleSmoothedToUint8',true);
assert(isa(SmokeSmoothedUint8,'uint8'),'Detection preprocessing helper did not return uint8 when requested.');

DetrendedMatrix = detrend_custom(single([1:12; 2:2:24]),2);
DetrendedStack = detrend_custom(single(RawData),3);
assert(isequal(size(DetrendedMatrix),[2 12]) && isequal(size(DetrendedStack),size(RawData)), ...
    'Shared detrend helper returned unexpected output sizes.');

DetectionParams = struct();
DetectionParams.percentileThreshold = 50;
DetectionParams.minArea = 1;
DetectionParams.maxArea = Inf;
DetectionParams.minCircularity = 0;
DetectionParams.maxOutsideFraction = 1;
DetectionParams.frameTransform = 'mat2gray';
DetectedRegions = detectFrameRegionCandidates(single(RawData),true(size(RawData,1),size(RawData,2)),DetectionParams);
assert(numel(DetectedRegions)==size(RawData,3),'Frame-candidate detector returned unexpected frame count.');
[PutativeEventMask,ForbiddenPixels] = computeFrameDifferenceEventMask(uint8(RawData));
assert(islogical(PutativeEventMask),'Frame-difference event-mask helper returned a non-logical mask.');
assert(~isempty(ForbiddenPixels),'Frame-difference event-mask helper returned empty forbidden edge pixels.');

end

