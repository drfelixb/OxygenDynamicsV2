function testPairAnalysis()

Hypoxia = false(20,20,8);
Hypoxia(4:6,4:6,2:4) = true;
Amyloid = ones(20,20);
Amyloid(3:5,3:5) = 10;
Options = struct('PixelSizeMicrometers',1,'AmyloidThreshold',0.5, ...
    'HypoxiaThreshold',0.05,'MinimumPlaqueAreaPixels',2, ...
    'RegionSigmaMicrometers',1,'CoarseSigmaMicrometers',4, ...
    'NumPermutations',20,'RandomSeed',7);

First = analyzeHypoxiaAmyloidPair(Hypoxia,Amyloid,Options);
Second = analyzeHypoxiaAmyloidPair(Hypoxia,Amyloid,Options);
assert(any(First.amyloid_mask(:)) && any(First.hypoxia_mask(:)), ...
    'Synthetic pair analysis did not detect expected masks.');
assert(isequaln(First.null_overlap_fraction,Second.null_overlap_fraction), ...
    'Spatial permutations were not deterministic for a fixed seed.');
assert(isequaln(First.null_correlation,Second.null_correlation), ...
    'Correlation permutations were not deterministic for a fixed seed.');
assert(isequaln(First.null_shifts_pixels,Second.null_shifts_pixels) && ...
    size(First.null_shifts_pixels,1)==Options.NumPermutations, ...
    'Circular-shift coordinates were not retained reproducibly.');

mustError(@() analyzeHypoxiaAmyloidPair(Hypoxia,ones(19,20),Options), ...
    'HypoxiaAmyloid:DimensionMismatch');
end

function testEventProperties()

[SinkStack,OxySinkAreaAll,SinkTable] = syntheticSinkData();
[Footprints,TrackedPixels] = reconstructHypoxicEventFootprints( ...
    SinkStack,OxySinkAreaAll,SinkTable);
assert(numel(Footprints)==3 && nnz(~cellfun(@isempty,TrackedPixels))==6, ...
    'Event-footprint reconstruction returned unexpected event/frame counts.');

PlaqueMask = false(20,20);
PlaqueMask(3:4,3:4) = true;
Options = struct('NearThresholdMicrometers',5, ...
    'SensitivityThresholdsMicrometers',[2 5 10], ...
    'MinimumObservationsPerStratum',1, ...
    'DistanceVariable','EdgeDistance_um', ...
    'SpatialNullShiftsPixels',[0 0; 3 4]);
Analysis = analyzeHypoxiaAmyloidEventProperties(Footprints,SinkTable, ...
    PlaqueMask,1,2,Options);

assert(height(Analysis.EventTable)==3 && height(Analysis.PocketTable)==2, ...
    'Amplitude-free event/pocket tables have unexpected sizes.');
assert(Analysis.EventTable.EdgeDistance_um(1)==1, ...
    'Nearest edge-to-edge distance was not calculated as expected.');
assert(Analysis.EventTable.DurationSec(1)==1 && ...
    Analysis.EventTable.Area_um2(1)==4, ...
    'Duration or event area calibration was incorrect.');
assert(Analysis.PocketTable.RecurrenceCount(1)==2 && ...
    Analysis.PocketTable.RecurrenceCount(2)==1, ...
    'Recurrence was not summarized once per tracked pocket.');
assert(height(Analysis.Summary.Correlations)==3 && ...
    height(Analysis.Summary.Thresholds)==9, ...
    'Continuous or threshold-sensitivity summaries are incomplete.');
assert(height(Analysis.SpatialNull)==18 && ...
    all(ismember(["Duration","SpatialSize","Recurrence"], ...
    unique(Analysis.SpatialNull.Property))), ...
    'Property-specific circular-shift null rows are incomplete.');
end

function testNoPlaqueBehavior()

[SinkStack,OxySinkAreaAll,SinkTable] = syntheticSinkData();
[Footprints,~] = reconstructHypoxicEventFootprints( ...
    SinkStack,OxySinkAreaAll,SinkTable);
Analysis = analyzeHypoxiaAmyloidEventProperties(Footprints,SinkTable, ...
    false(20,20),1,2,struct('MinimumObservationsPerStratum',1));
assert(all(isnan(Analysis.EventTable.EdgeDistance_um)) && ...
    all(isnan(Analysis.PocketTable.EdgeDistance_um)), ...
    'No-plaque distances must remain NaN.');
assert(all(isnan(Analysis.Summary.Correlations.SpearmanRho)), ...
    'No-plaque correlations must remain NaN.');
end

function testOptionalCsvColumn()

Required = table({'R1'},{''},{''},{''},{'M1'},{'APP'},{'C'},{'D'}, ...
    {'P'},1,2.5,'VariableNames',requiredWrapperInputColumns());
