assert(isempty(AmyloidFiles{1}), ...
    'Missing optional AmyloidFile column should resolve to blank values.');

Required.AmyloidFile = {'methoxy.tif'};
[~,~,~,~,~,~,~,~,~,~,~,AmyloidFiles] = unpackWrapperInputTable(Required);
assert(strcmp(AmyloidFiles{1},'methoxy.tif'), ...
    'Optional AmyloidFile column was not unpacked correctly.');
end

