function testRecordingAdapter()

Root = fullfile(tempdir,['HypoxiaAmyloidTest_', ...
    char(datetime('now','Format','yyyyMMddHHmmssSSS'))]);
RecordingFolder = fullfile(Root,'Mouse1','Recording1');
SinksFolder = fullfile(RecordingFolder,'OxygenSinks_Output');
mkdir(SinksFolder);
Cleanup = onCleanup(@() removeTestFolder(Root));

[SinkStack,OxySinkArea_all,Table_OxygenSinks_Out] = syntheticSinkData();
saveastiff(uint16(SinkStack),fullfile(SinksFolder,'IM_OxySinks_BWSmoke.tif'), ...
    struct('overwrite',true));
save(fullfile(SinksFolder,'OxygenSinks_UrefinedSmoke.mat'), ...
    'Table_OxygenSinks_Out','OxySinkArea_all');

Amyloid = uint16(ones(20,20)*100);
Amyloid(3:4,3:4) = 1000;
AmyloidFile = fullfile(RecordingFolder,'methoxy_x04.tif');
imwrite(Amyloid,AmyloidFile);
AmyloidFolder = fullfile(RecordingFolder,'methoxy');
mkdir(AmyloidFolder);
FolderAmyloidFile = fullfile(AmyloidFolder,'methoxy_x04.tif');
imwrite(Amyloid,FolderAmyloidFile);
assert(strcmp(resolveOptionalRecordingFile('methoxy',RecordingFolder), ...
    FolderAmyloidFile), ...
    'Amyloid folder input did not resolve its single TIFF.');

Metadata = createRecordingMetadata('Mouse1','APP','None', ...
    'FourMonthAPP','MethoxyX04');
Options = struct('OverwriteOutputs',true,'SaveFigures',true, ...
    'PairOptions',struct('AmyloidThreshold',0.5,'NumPermutations',5, ...
    'RegionSigmaMicrometers',1,'CoarseSigmaMicrometers',4), ...
    'PropertyOptions',struct('NearThresholdMicrometers',5, ...
    'SensitivityThresholdsMicrometers',[2 5 10], ...
    'MinimumObservationsPerStratum',1, ...
    'DistanceVariable','CentroidDistance_um'));
Result = runHypoxiaAmyloidRecordingAnalysis(RecordingFolder,'methoxy', ...
    Metadata,2,1,Options);

assert(isfile(fullfile(Result.OutputFolder,'HypoxiaAmyloid_EventMetrics.csv')) && ...
    isfile(fullfile(Result.OutputFolder,'HypoxiaAmyloid_Result.mat')) && ...
    isfile(fullfile(Result.OutputFolder,'HypoxiaAmyloid_QC.png')) && ...
    isfile(fullfile(Result.OutputFolder, ...
    'HypoxiaAmyloid_PropertySpatialNull.csv')) && ...
    height(Result.Properties.EventTable)==3 && Result.Age=="4 months", ...
    'Recording adapter did not create the expected event outputs.');

CohortOptions = struct('PropertyOptions',Options.PropertyOptions, ...
    'NumPermutations',50,'BootstrapIterations',50,'RandomSeed',3);
Cohort = runHypoxiaAmyloidCohortSummary({Result},Root,CohortOptions);
assert(isfile(fullfile(Cohort.OutputFolder,'AnimalCorrelations.csv')) && ...
    isfile(fullfile(Cohort.OutputFolder,'PerPocketTable.csv')) && ...
    isfile(fullfile(Cohort.OutputFolder,'AnimalInclusion.csv')) && ...
    isfile(fullfile(Cohort.OutputFolder,'GroupResults.csv')) && ...
    isfile(fullfile(Cohort.OutputFolder,'GroupDefinitions.csv')) && ...
    isfile(fullfile(Cohort.OutputFolder,'AnalysisAvailability.csv')) && ...
    isfile(fullfile(Cohort.OutputFolder,'TreatmentComparisonResults.csv')) && ...
    isfile(fullfile(Cohort.OutputFolder,'FactorialInteractionResults.csv')) && ...
    isfile(fullfile(Cohort.OutputFolder,'AgeComparisonResults.csv')) && ...
    isfile(fullfile(Cohort.OutputFolder, ...
    'HypoxiaAmyloid_Figure2Candidate.png')) && ...
    any(Cohort.GroupResults.Scope=="None | APP") && ...
    all(ismember({'Condition','DrugID','AnalysisGroup'}, ...
    Cohort.AnimalThresholds.Properties.VariableNames)), ...
    'Cohort aggregation did not create the expected animal-level outputs.');
end

function [SinkStack,OxySinkAreaAll,SinkTable] = syntheticSinkData()

SinkStack = false(20,20,10);
NearPixels = blockPixels([5 4],20);
FarPixels = blockPixels([15 15],20);
SinkStack(NearPixels+20*20*(2-1)) = true;
SinkStack(NearPixels+20*20*(3-1)) = true;
SinkStack(FarPixels+20*20*(5-1)) = true;
SinkStack(FarPixels+20*20*(6-1)) = true;
SinkStack(NearPixels+20*20*(8-1)) = true;
SinkStack(NearPixels+20*20*(9-1)) = true;

OxySinkAreaAll = cell(2,10);
OxySinkAreaAll(1,[2 3 8 9]) = {4};
OxySinkAreaAll(2,[5 6]) = {4};
SinkTable = table([2;1],{[2 2];2},{NearPixels;FarPixels}, ...
    'VariableNames',{'NumOxySinkEvents','Duration','OxySink_Pxls_all'});
end

function Pixels = blockPixels(TopLeft,ImageHeight)

Rows = TopLeft(1)+(0:1);
Cols = TopLeft(2)+(0:1);
[ColGrid,RowGrid] = meshgrid(Cols,Rows);
Pixels = sub2ind([ImageHeight ImageHeight],RowGrid(:),ColGrid(:));
end

function mustError(FunctionHandle,ExpectedIdentifier)

DidError = false;
try
    FunctionHandle();
catch ME
    DidError = strcmp(ME.identifier,ExpectedIdentifier);
end
assert(DidError,'Expected error %s was not raised.',ExpectedIdentifier);
end

function removeTestFolder(Folder)

if isfolder(Folder)
    rmdir(Folder,'s');
end
end
