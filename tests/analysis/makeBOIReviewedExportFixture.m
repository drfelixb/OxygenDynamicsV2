function F=makeBOIReviewedExportFixture(root,mode)
% Finite synthetic saved results/audit/revisions. No original image files.
if nargin<2,mode='missing';end
if ~isfolder(root),mkdir(root);end
RecordingRegistry=table("synthetic-recording","experiment","0007","baseline","none","genotype","promoter",false,100,1,100,100,"synthetic-raw", ...
    'VariableNames',{'RecordingID','Experiment','Mouse','Condition','DrugID','Genotype','Promoter','PuffStim', ...
    'NFrames','SampleF','RecordingDuration_sec','RecordingArea_um2','RawSHA256'});
E=repmat(RecordingRegistry,2,1);E.SinkID=[1;2];E.EventID=[1;1];E.StartFrame=[10;20];E.EndFrame=[11;21];E.DurationSec=[2;2];
E.NormOxySinkAmpPercent=[10;NaN];if strcmp(mode,'complete'),E.NormOxySinkAmpPercent(2)=20;end
E.EventArea_um2=[4;3];E.RecAreaSize=[100;100];E.RecDuration=[100;100];
HypoxicBurden=createHypoxicBurdenMetrics(E,table(),table(),RecordingRegistry);
masters={fullfile(root,'offline-sink.mat'),fullfile(root,'offline-surge.mat')};
StatsInfo=struct('Recordings',struct('Path','synthetic-recording','SinksMatFile',masters{1},'SurgesMatFile',masters{2}));
mat=fullfile(root,'DataOutput.mat');save(mat,'HypoxicBurden','RecordingRegistry','StatsInfo');
Audit=table(repmat("synthetic-recording",2,1),repmat("sink",2,1),[1;2],[1;1],[10;20],[11;21],[10;20],[11;21], ...
    repmat(4,2,1),repmat(9,2,1),repmat(100,2,1),repmat("valid",2,1),[10;20],[10;20],true(2,1),false(2,1),repmat("synthetic-raw",2,1), ...
    'VariableNames',{'RecordingID','EventType','SiteID','EventID','StartFrame','EndFrame','DetectedStartFrame','DetectedEndFrame', ...
    'FootprintPixels','BaselineWindowFrames','RecomputedBaseline','RecomputedStatus','StoredAmplitude','RecomputedAmplitude','MeasurementMatches','WrongDirection','SourceRawSHA256'});
raw=100*ones(100,1);raw(18:22)=[95;80;70;90;100];Traces=cell(2,1);
for k=1:2,Traces{k}=struct('Raw',raw,'Footprint',(1:4)','CleanBaselineFrames',(1:9)','DetectedFrames',(Audit.StartFrame(k):Audit.EndFrame(k))');end
AnalysisInfo=struct('RawFile',fullfile(root,'offline-original.tif'),'RawSHA256','synthetic-raw','NFrames',100,'FrameSize',[4 4],'AnalysisParams',struct('fs',1,'PixelSize',1),'RecordingAreaUm2',100,'DenoisedFile','','DenoisedSHA256','');
audit=fullfile(root,'event-amplitude-audit.mat');save(audit,'Audit','Traces','AnalysisInfo');
Table_OxygenSinkEvents_Out=E;save(masters{1},'Table_OxygenSinkEvents_Out','AnalysisInfo');
SyntheticSurge=true;save(masters{2},'SyntheticSurge');
receipt=struct('Schema','boi-created-event-audit-1','AuditSHA256',oxygenFileSHA256(audit),'SourceSHA256','synthetic-raw', ...
    'MasterSHA256',{{oxygenFileSHA256(masters{1}),oxygenFileSHA256(masters{2})}},'MasterPaths',{masters});writeBOIRunJSON(fullfile(root,'AuditCreationReceipt.json'),receipt);
R=loadBOIEventReview(audit);annotation=struct('Status','not_recognized','OnsetFrames',[],'RecoveryFrames',[], ...
    'PreferredOnsetFrame',[],'PreferredRecoveryFrame',[],'Reviewer','Synthetic software fixture','Reason','Synthetic rejection only; not researcher evidence');
R.BoundaryReview=saveBOIBoundaryReview(R,1,annotation,fullfile(root,'review-01.json'));
F=struct('Root',root,'StatsMAT',mat,'ReviewPaths',{{R.BoundaryReview.Path}},'EventFolders',{{}}, ...
    'OutputFolder',fullfile(root,'new reviewed export'),'Automatic',HypoxicBurden,'Registry',RecordingRegistry,'AuditPath',audit);
if ismember(mode,{'legacy','area-incomplete','area-complete'})
    annotation.Status='recognized';annotation.OnsetFrames=18;annotation.PreferredOnsetFrame=18;
    annotation.RecoveryFrames=22;annotation.PreferredRecoveryFrame=22;
    R.BoundaryReview=saveBOIBoundaryReview(R,2,annotation,fullfile(root,'review-02.json'),R.BoundaryReview);
    F.ReviewPaths={R.BoundaryReview.Path};B=getBOIBoundaryReview(R,2);
    J=struct('Schema','boi-researcher-reference-acceptance-1','DecisionID','SYNTHETIC-ONLY','Reviewer','Synthetic software fixture', ...
        'RecordedUTC','2026-10-31T00:00:00Z','BoundaryReviewSHA256',R.BoundaryReview.SHA256,'AuditRow',2, ...
        'SavedEvent',B.Event,'BoundaryAnnotationUnchanged',B.Annotation,'AcceptedReferenceFrames',(12:17)', ...
        'AcceptedSampleCount',6,'ReferenceJudgment','accepted_as_synthetic_reference');
    reference=fullfile(root,'reference.json');writeBOIRunJSON(reference,J);referenceHash=oxygenFileSHA256(reference);
    event=fullfile(root,'approved synthetic event');
    if strcmp(mode,'legacy')
        mkdir(event);
        D=struct('Schema','boi-reviewed-single-event-burden-1','RecordingID','synthetic-recording','EventType','sink','AuditRow',2,'SiteID',2,'EventID',1, ...
            'OriginalAutomaticStartFrame',20,'OriginalAutomaticEndFrame',21,'StartFrame',18,'EndFrame',22,'DurationSec',5,'SampleHz',1, ...
            'RawSourceSHA256','synthetic-raw','BoundaryPath',R.BoundaryReview.Path,'BoundarySHA256',R.BoundaryReview.SHA256, ...
            'ReferencePath',reference,'ReferenceSHA256',referenceHash,'AuditPath',audit,'AuditSHA256',R.AuditSHA256, ...
            'ReferenceStartFrame',12,'ReferenceEndFrame',17,'ReferenceSamples',6,'RawReferenceMean',100,'RawMinimum',70, ...
            'BurdenAmplitudePercent',30,'BurdenArea_um2',3,'BurdenRecordingArea_um2',100,'BurdenRecordingDuration_sec',100, ...
            'PerEventBurdenContribution',450,'PerEventBurdenContribution_per_mm2_per_min',2700000, ...
            'AreaRemeasured',false,'AreaQualification','Synthetic legacy saved area; not researcher evidence', ...
            'OriginalResultsChanged',false,'GlobalDefaultsChanged',false,'RecordingTotalCalculated',false,'PartialSumCalculated',false);
        writeBOIRunJSON(fullfile(event,'ReviewedEventBurden.json'),D);writeBOIRunJSON(fullfile(event,'Status.json'),struct('Status','complete'));
        manifest=struct('Path','ReviewedEventBurden.json','SHA256',oxygenFileSHA256(fullfile(event,'ReviewedEventBurden.json')));
        writeBOIRunJSON(fullfile(event,'Checksums.json'),manifest);
    else
        measurementFolder=fullfile(root,'approved synthetic measurement');mkdir(measurementFolder);
        M=struct('Schema','boi-reviewed-amplitude-duration-evidence-1','AuditSHA256',R.AuditSHA256, ...
            'RecordingID','synthetic-recording','EventType','sink','SiteID',2,'EventID',1, ...
            'BoundaryPath',R.BoundaryReview.Path,'BoundarySHA256',R.BoundaryReview.SHA256, ...
            'ReferencePath',reference,'ReferenceSHA256',referenceHash,'StartFrame',18,'EndFrame',22, ...
            'DurationSec',5,'RawAmplitudePercent',30,'RawReferenceMean',100,'RawMinimum',70, ...
            'OriginalAutomaticStartFrame',20,'OriginalAutomaticEndFrame',21,'FixedTraceFootprintPixels',4);
        writeBOIRunJSON(fullfile(measurementFolder,'Status.json'),struct('Status','complete'));
        writeBOIRunJSON(fullfile(measurementFolder,'ReviewedMeasurement.json'),M);
        writeBOIRunJSON(fullfile(measurementFolder,'Checksums.json'),struct('Path','ReviewedMeasurement.json', ...
            'SHA256',oxygenFileSHA256(fullfile(measurementFolder,'ReviewedMeasurement.json'))));
        D=createBOIAreaReview(R,2,measurementFolder,[]);D.Reviewer='Synthetic software fixture';D.Reason='Synthetic test only';
        if strcmp(mode,'area-complete')
            for k=1:numel(D.FrameDecisions)
                D.FrameDecisions(k).Status='accepted';D.FrameDecisions(k).Pixels=(1:3)';
                D.FrameDecisions(k).Reviewer='Synthetic software fixture';D.FrameDecisions(k).DecidedUTC='2026-10-31T00:00:00Z';
            end
        end
        saveBOIAreaReview(D,event);
    end
    loadBOIReviewedBurdenEvent(event);F.EventFolders={event};
end
end
